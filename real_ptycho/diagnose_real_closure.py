"""Read-only first-step closure diagnostic; never runs a reconstruction.

Compare measured diffraction with noiseless diffraction generated by the SAME
experimental-grid forward operator. A successful mPIE reconstruction supplies
surrogate fields ONLY to manufacture test measurements, never training initial
fields. Synthetic fields are not claimed to be experimental ground truth.

Only the algebraically equivalent first Adam head/probe step is evaluated. No
production solver, parameter, input file, or optimizer is changed.
"""
import argparse
from datetime import datetime
import gc
import json
from pathlib import Path

import h5py
import numpy as np
import torch

from core import UNet, Propagator, chunked_data, mpie_geometry, select_center_grid, preserve_buffers
from diagnose_center_peak import (neutral_head_parameters, decode_heads,
                                  first_adam_head_field, feature_stats, peak, input_stats)
from initialization import initial_fields
from run import network_input


HERE = Path(__file__).resolve().parent


def field_metrics(field, center):
    a = field.abs()
    cy, cx = center
    center_energy = a[cy-64:cy+64, cx-64:cx+64].square().sum()
    return dict(peak=peak(a.detach().cpu().numpy()),
                center128_l2_energy_fraction=float(center_energy/a.square().sum().clamp_min(1e-30)))


def compare_first_step(name, data, o0, p0, positions, source_note, update_probe=True):
    torch.manual_seed(0)
    side, n = o0.shape[-1], p0.shape[-1]
    net = UNet(64, 16, checkpoint_blocks=True).cuda()
    net.set_initial_object(o0)
    x = network_input(data, side, 64, 'cuda')
    saved = {}
    hook = net.d1.register_forward_hook(lambda module, inp, out: saved.update(phi=out.detach().clone()))
    with preserve_buffers(net), torch.no_grad():
        initial = net(x).detach()
    hook.remove()
    phi = saved.pop('phi')
    prop = Propagator(positions, n, sampling='mpie-integer')
    go, gp, before = chunked_data(initial, p0, range(len(data)), data, prop, 1)
    parameters = neutral_head_parameters(net)
    obj = decode_heads(phi, parameters, net.initial_amp_offset)
    gradients = torch.autograd.grad(obj, parameters, grad_outputs=go)
    virtual = first_adam_head_field(phi, parameters, gradients, net.initial_amp_offset)
    # The real and imaginary probe arrays have separate Adam moments.
    with torch.no_grad():
        probe_after = torch.complex(p0.real-.005*gp.real/(gp.real.abs()+1e-8),
                                    p0.imag-.005*gp.imag/(gp.imag.abs()+1e-8))
        if not update_probe:
            probe_after = p0
        pixel_after = torch.complex(initial.real-.0005*go.real/(go.real.abs()+1e-8),
                                    initial.imag-.0005*go.imag/(go.imag.abs()+1e-8))
        delta = virtual-initial
        direction_cosine = float((-go.conj()*delta).real.sum()/(go.norm()*delta.norm()).clamp_min(1e-30))
        # At O0>0 and phase=0, real gradient is the amplitude derivative.
        amplitude_descent = -go.real
        cy = cx = side//2
        physical_positive = amplitude_descent.clamp_min(0)
        displacement = delta.abs()  # complex-field displacement, not signed amplitude
        signed_delta_amplitude = virtual.abs()-initial.abs()
        same_sign = (signed_delta_amplitude*amplitude_descent > 0)
        weight = signed_delta_amplitude.abs()
        sign_agreement = float(weight[same_sign].sum()/weight.sum().clamp_min(1e-30))
        signed_physical_center = amplitude_descent[cy-64:cy+64, cx-64:cx+64]
        center_rise_fraction = float((signed_physical_center > 0).float().mean())
    only_o = chunked_data(virtual, p0, range(len(data)), data, prop, 1, False)[2]
    both = chunked_data(virtual, probe_after, range(len(data)), data, prop, 1, False)[2]
    report = dict(name=name, source=source_note, gain=1, feature_norm='none',
                  probe_mode='joint_first_step' if update_probe else 'surrogate_truth_fixed_diagnostic_only',
                  initial_field_max_error=float((initial-o0).abs().max()),
                  input=input_stats(x), features=feature_stats(phi),
                  first_virtual_object_peak=peak(virtual.abs().cpu().numpy()),
                  first_virtual_object_min=float(virtual.abs().min()),
                  pixel_adam_object_peak=peak(pixel_after.abs().cpu().numpy()),
                  physical_gradient=field_metrics(go, (cy, cx)),
                  positive_amplitude_descent=field_metrics(physical_positive, (cy, cx)),
                  center128_physical_amplitude_descent_positive_fraction=center_rise_fraction,
                  center128_mean_amplitude_descent=float(signed_physical_center.mean()),
                  network_displacement=field_metrics(displacement, (cy, cx)),
                  field_descent_direction_cosine=direction_cosine,
                  amplitude_step_weighted_sign_agreement=sign_agreement,
                  before=before, after_object_only=only_o, after_both=both)
    print(json.dumps(report), flush=True)
    maps = dict(input_mean=x.mean(1)[0].cpu().numpy(),
                negative_amplitude_gradient=amplitude_descent.cpu().numpy(),
                network_amplitude_delta=signed_delta_amplitude.cpu().numpy(),
                first_object_amplitude=virtual.abs().cpu().numpy())
    del net, x, saved, phi, go, gp, obj, parameters, gradients, virtual
    gc.collect()
    torch.cuda.empty_cache()
    return report, maps


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--data', type=Path, default=HERE.parent/'experiment/ptydata_33.h5')
    p.add_argument('--reference', type=Path,
                   default=Path('C:/Users/kennyzz/Downloads/reconstruction_mpie_100ITER.npz'))
    p.add_argument('--out', type=Path,
                   default=HERE/'results'/datetime.now().strftime('real_closure_%Y%m%d_%H%M%S_%f'))
    args = p.parse_args()
    if args.out.exists():
        p.error('Choose a fresh output directory')
    if not torch.cuda.is_available():
        p.error('This bounded full-size diagnostic requires CUDA')
    args.out.mkdir(parents=True)
    torch.set_num_threads(2)
    torch.backends.cudnn.benchmark = False
    torch.backends.cudnn.deterministic = True
    with np.load(args.reference) as z:
        cfg = json.loads(str(z['config']))
        oref_full = z['obj_rec']
        pref = torch.from_numpy(z['probe_rec']).cuda()
        reference_ids = z['original_frame_ids']
        reference_positions = z['positions_px']
    with h5py.File(args.data, 'r') as f:
        ids, coords, groups, _ = select_center_grid(f['positionx'][()], 225)
        positions, side, dx, old, metadata = mpie_geometry(coords, 1024, 632.8, 6., 3.76)
        group = groups[0]
        measured = np.stack([f['ptychogramx'][int(ids[i]),488:1512,488:1512].astype('float32')
                             /cfg['intensity_mean_before_scaling'] for i in group])
    oy, ox = metadata['network_origin_in_reference_yx']
    for i, original_id in enumerate(ids):
        ref_i = int(np.flatnonzero(reference_ids == original_id)[0])
        np.testing.assert_array_equal(reference_positions[ref_i], positions[i]+[oy, ox])
    oref = torch.from_numpy(oref_full[oy:oy+side,ox:ox+side].copy()).cuda()
    del oref_full
    prop = Propagator(positions, 1024, sampling='mpie-integer')
    synthetic = np.empty_like(measured)
    slot = {int(i): j for j, i in enumerate(group)}
    energy = 0.
    with torch.no_grad():
        for i in range(225):
            intensity = prop.amplitude(oref, pref, [i]).square()[0]
            energy += float(intensity.sum(dtype=torch.float64))
            if i in slot:
                synthetic[slot[i]] = intensity.cpu().numpy()
    synthetic_mean = energy/(225*1024**2)
    synthetic /= synthetic_mean
    # A second noiseless control has an exactly constant object and the same
    # reference probe. There are no USAF structures to recover in this control.
    with torch.no_grad():
        plain_object = torch.ones_like(oref)
        plain_frame = prop.amplitude(plain_object, pref, [0]).square()[0]
        plain_mean = float(plain_frame.mean(dtype=torch.float64))
        plain = np.repeat((plain_frame.cpu().numpy()/plain_mean)[None], len(group), axis=0)
    o0_np, p0_np, _ = initial_fields('mpie', 1024, side, old, dx*1e6, 0)
    o0, p0 = torch.from_numpy(o0_np).cuda(), torch.from_numpy(p0_np).cuda()
    group_prop = Propagator(positions[group], 1024, sampling='mpie-integer')
    closure = chunked_data(oref, pref/np.sqrt(synthetic_mean), range(len(group)),
                           synthetic, group_prop, 1, False)[2]
    plain_closure = chunked_data(plain_object, pref/np.sqrt(plain_mean), range(len(group)),
                                 plain, group_prop, 1, False)[2]
    if max(closure['relative_amplitude_rmse'], plain_closure['relative_amplitude_rmse']) > 1e-5:
        raise RuntimeError('Synthetic closure failed')
    cases = [('measured', measured, 'Original measured A64; shared measured intensity normalization'),
             ('noiseless_reference', synthetic,
              'Exact current forward of mPIE surrogate O/P; common mean over all 225 frames normalized to 1'),
             ('noiseless_constant_object', plain,
              'Exact current forward of O=1 and mPIE surrogate P; all measurements identical')]
    report = dict(reference=str(args.reference), data=str(args.data),
                  device=torch.cuda.get_device_name(0), seed=0,
                  synthetic_intensity_mean_before_scaling=synthetic_mean,
                  constant_object_intensity_mean_before_scaling=plain_mean,
                  synthetic_fields_are_surrogates_not_experimental_ground_truth=True,
                  synthetic_closure=closure, constant_object_closure=plain_closure,
                  optimizer_updates=0, first_step_algebraic_replays=len(cases)+1,
                  network_lr=.0005, probe_lr=.005, tgv=0, nlm=0,
                  geometry=dict(side=side, fft=1024, frames=64,
                                network_origin_in_reference_yx=[oy,ox]), results=[])
    all_maps = {}
    for name, data, note in cases:
        row, maps = compare_first_step(name, data, o0, p0, positions[group], note)
        report['results'].append(row)
        all_maps.update({name+'_'+k: v for k,v in maps.items()})
    # Same synthetic USAF measurements and network features, but remove blind
    # probe estimation from this diagnostic by holding its exact generator P.
    name = 'noiseless_reference_known_probe'
    row, maps = compare_first_step(name, synthetic, o0, pref/np.sqrt(synthetic_mean), positions[group],
                                  'Same noiseless surrogate USAF data; exact generating probe held fixed, NOT a production initialization',
                                  update_probe=False)
    report['results'].append(row)
    all_maps.update({name+'_'+k: v for k,v in maps.items()})
    (args.out/'metrics.json').write_text(json.dumps(report, indent=2), encoding='utf-8')
    np.savez_compressed(args.out/'maps.npz', **all_maps)
    print('OUTPUT', args.out.resolve(), flush=True)


if __name__ == '__main__':
    main()
